import { type Alert } from "../schemas/live.js";
import { buildAlert } from "./detectors.js";
import { enAlerts, hiAlerts } from "../i18n/index.js";

export interface IncidentEvent {
  atSec: number;
  type: "STALL" | "LIKELY_SKIP" | "GHOST";
  busId?: string;
  routeId?: string;
  stopId?: string;
  durationSec?: number;
  scheduledDepartureSec?: number;
  description: string;
}

export interface IncidentSchedule {
  seed?: number;
  startHour?: number;
  events: IncidentEvent[];
}

