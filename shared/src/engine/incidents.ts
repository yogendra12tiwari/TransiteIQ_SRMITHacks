function matchesBus(busId: string, targetId?: string): boolean {
  if (!targetId) return false;
  if (busId === targetId) return true;
  const cleanA = busId.replace(/^bus_/, "").replace(/^route_/, "");
  const cleanB = targetId.replace(/^bus_/, "").replace(/^route_/, "");
  return cleanA === cleanB;
}

function matchesRoute(routeId: string, targetId?: string): boolean {
  if (!targetId) return false;
  if (routeId === targetId) return true;
  const cleanA = routeId.replace(/^route_/, "");
  const cleanB = targetId.replace(/^route_/, "");
  return cleanA === cleanB;
}

export class IncidentRunner {
  private events: IncidentEvent[];

  constructor(schedule?: IncidentSchedule | IncidentEvent[]) {
    if (Array.isArray(schedule)) {
      this.events = schedule;
    } else if (schedule?.events) {
      this.events = schedule.events;
    } else {
      this.events = [];
    }
  }

  /**
   * Applies scripted incident events to the simulation state at elapsedSec seconds (M3-23).
   * Returns the updated SimState and any active alerts generated by incidents.
   */
  apply(
    state: SimState,
    elapsedSec: number,
    network: Network,
    nowMs: number = state.simTimeMs,
  ): { state: SimState; alerts: Alert[] } {
    const alerts: Alert[] = [];
    const stalledBusIds = new Set<string>();

    for (const event of this.events) {
      if (elapsedSec < event.atSec) {
        continue;
      }

      if (event.type === "STALL" && event.busId) {
        const stallEnd = event.atSec + (event.durationSec ?? 360);
        if (elapsedSec < stallEnd) {
          const bus = state.buses.find((b) => matchesBus(b.id, event.busId));
          const effectiveBusId = bus ? bus.id : event.busId;
          stalledBusIds.add(effectiveBusId);

          const stallMin = Math.round(((elapsedSec - event.atSec) / 60) * 10) / 10;
          const route = network.routes.find((r) => r.id === bus?.routeId);

          alerts.push(
            buildAlert({
              id: `alert_incident_stall_${event.busId}`,
              type: "STALL",
              severity: "high",
              message: enAlerts.stall(event.busId, Math.max(stallMin, 1.0)),
              messageHi: hiAlerts.stall(event.busId, Math.max(stallMin, 1.0)),
              affectedStopIds: route ? route.stopIds : [],
              createdAt: nowMs - (elapsedSec - event.atSec) * 1000,
            }),
          );
        }
      } else if (event.type === "LIKELY_SKIP" && event.busId && event.stopId) {
        const stop = network.stops.find((s) => s.id === event.stopId);
        const stopName = stop ? stop.name : event.stopId;

        alerts.push(
          buildAlert({
            id: `alert_incident_skip_${event.busId}_${event.stopId}`,
            type: "LIKELY_SKIP",
            severity: "high",
            message: enAlerts.likelySkip(event.busId, stopName),
            messageHi: hiAlerts.likelySkip(event.busId, stopName),
            affectedStopIds: [event.stopId],
            createdAt: nowMs,
          }),
        );
      } else if (event.type === "GHOST" && event.routeId) {
        const route = network.routes.find((r) => matchesRoute(r.id, event.routeId));
        const routeName = route ? route.name : event.routeId;
        const departureSec = event.scheduledDepartureSec ?? event.atSec - 30;
        const ghostMin = Math.max(1, Math.floor((elapsedSec - departureSec) / 60));

        alerts.push(
          buildAlert({
            id: `alert_incident_ghost_${event.routeId}`,
            type: "GHOST_BUS",
            severity: "high",
            message: enAlerts.ghost(routeName, ghostMin),
            messageHi: hiAlerts.ghost(routeName, ghostMin),
            affectedStopIds: route ? route.stopIds : [],
            createdAt: nowMs,
          }),
        );
      }
    }

    // Update bus state for stalled buses
    const updatedBuses = state.buses.map((bus) => {
      if (stalledBusIds.has(bus.id)) {
        return {
          ...bus,
          speedMps: 0,
          status: "STALLED" as const,
        };
      } else if (bus.status === "STALLED" && !stalledBusIds.has(bus.id)) {
        return {
          ...bus,
          status: "RUNNING" as const,
        };
      }
      return bus;
    });

    return {
      state: {
        ...state,
        buses: updatedBuses,
      },
      alerts,
    };
  }
}
